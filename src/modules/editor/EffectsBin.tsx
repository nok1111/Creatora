/** Display section (the 8 library categories) for a catalog item. */
function sectionOf(cat: EffectCategory, id: string): string {
  const e = fxEntry(id);
  if (e) return e.category;
  if (cat === "merge") return "transitions";
  if (cat === "start") return "intro";
  if (cat === "end") return "outro";
  return ["pulse", "shake", "zoomPunch"].includes(id) ? "motion" : "cinematic";
}

export function EffectsBin() {
  const { t } = useTranslation();
  const [section, setSection] = useState<string>("all");
  const sections = Array.from(
    new Set(FX_CATALOG.flatMap((c) => c.items.map((i) => sectionOf(c.id, i.id)))),
  );
  const [showAll] = [section === "all"];
  return (
    <div className="flex h-full flex-col overflow-y-auto">
      <div className="flex flex-wrap gap-1 border-b border-border/60 px-2 py-1.5">
        {["all", ...sections].map((s2) => (
          <button
            key={s2}
            onClick={() => setSection(s2)}
            className={`rounded-full border px-2 py-0.5 text-[10px] ${section === s2 ? "border-primary bg-primary/15 text-foreground" : "border-border text-muted-foreground hover:bg-accent"}`}
          >
            {s2 === "all"
              ? "All"
              : (FX_CATEGORY_LABELS[s2] ??
                s2.replace(/[-_]/g, " ").replace(/\b\w/g, (ch) => ch.toUpperCase()))}
          </button>
        ))}
      </div>
      {FX_CATALOG.map((cat) => {
        const items = cat.items.filter((i) => showAll || sectionOf(cat.id, i.id) === section);
        if (!items.length) return null;
        return (
          <div key={cat.id} className="border-b border-border/60">
            <div className="flex items-center gap-1.5 px-2.5 py-1.5 text-[10px] font-medium uppercase tracking-wide text-muted-foreground">
              <cat.icon className="size-3" />
              {t(cat.labelKey)}
            </div>
            <div className="grid grid-cols-2 gap-1 px-2 pb-2">
              {items.map((item) => {
                const lacks = fxEntry(item.id) ? missingCapabilities(fxEntry(item.id)!) : [];
                return (
                  <div
                    key={item.id}
                    draggable={!lacks.length}
                    title={item.description ?? t("editor.fxDragHint")}
                    onDragStart={(e) => {
                      e.dataTransfer.setData(
                        "application/x-creatora-effect",
                        JSON.stringify({ category: cat.id, itemId: item.id }),
                      );
                      e.dataTransfer.effectAllowed = "copy";
                      setDragPayload({ effect: true, category: cat.id, itemId: item.id });
                    }}
                    onDragEnd={() => setDragPayload(null)}
                    className={`group relative flex cursor-grab flex-col gap-1 rounded border border-border bg-background/60 px-1.5 py-1.5 text-[11px] hover:border-primary/50 hover:bg-accent active:cursor-grabbing ${lacks.length ? "opacity-50" : ""}`}
                  >
                    {item.thumbImg && (
                      <img src={item.thumbImg} alt="" className="h-12 w-full rounded-sm object-cover" draggable={false} />
                    )}
                    {item.thumb && !item.thumbImg && <div className={`fxt ${item.thumb}`} aria-hidden />}
                    <div className="flex items-center gap-1.5">
                      <item.icon className="size-3.5 shrink-0 text-muted-foreground" />
                      <span className="truncate">{item.label}</span>
                    </div>
                    {item.description && (
                      <span className="line-clamp-2 text-[10px] leading-tight text-muted-foreground">
                        {item.description}
                      </span>
                    )}
                    <button
                      disabled={!!lacks.length}
                      title={lacks.length ? `Needs: ${lacks.join(", ")}` : "Apply to the selected clip"}
                      onClick={() =>
                        window.dispatchEvent(
                          new CustomEvent("creatora:apply-fx", { detail: { category: cat.id, itemId: item.id } }),
                        )
                      }
                      className="absolute right-1 top-1 hidden rounded bg-primary px-1.5 py-0.5 text-[10px] text-primary-foreground group-hover:block"
                    >
                      Apply
                    </button>
                  </div>
                );
              })}
            </div>
          </div>
        );
      })}
      <p className="px-2.5 py-2 text-[10px] leading-snug text-muted-foreground/70">
        {t("editor.fxBinFooter")}
      </p>
    </div>
  );
}
